def sheet(wb, title, headers, rows, widths, fill=None, note=None):
    ws = wb.create_sheet(title)
    r0 = 1
    if note:
        ws.cell(1, 1, note).font = Font(italic=True)
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
        ws.cell(1, 1).alignment = WRAP
        ws.row_dimensions[1].height = 45
        r0 = 2
    for c, h in enumerate(headers, 1):
        cell = ws.cell(r0, c, h)
        cell.fill, cell.font, cell.alignment = HEAD, Font(bold=True, color="FFFFFF"), WRAP
    for r, row in enumerate(rows, r0 + 1):
        for c, v in enumerate(row, 1):
            cell = ws.cell(r, c, v)
            cell.alignment = WRAP
            if fill:
                cell.fill = fill
    for c, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(c)].width = w
    ws.freeze_panes = ws.cell(r0 + 1, 1)
    return ws


